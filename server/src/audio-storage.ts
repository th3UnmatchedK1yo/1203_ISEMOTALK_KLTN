import fs from 'node:fs'
import path from 'node:path'
import type { DB } from './db'

export class UnsafeAudioPathError extends Error {}

function isInside(parent: string, child: string): boolean {
  const relative = path.relative(parent, child)
  return relative !== '' && relative !== '..' && !relative.startsWith(`..${path.sep}`) && !path.isAbsolute(relative)
}

function statIfPresent(file: string): fs.Stats | null {
  try { return fs.lstatSync(file) }
  catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT') return null
    throw error
  }
}

function ownedDirectory(uploadsDir: string, callId: string): string {
  // Call IDs generated by the API are single portable directory components.
  // Never turn an arbitrary legacy value into the target of recursive removal.
  if (!/^[A-Za-z0-9][A-Za-z0-9_-]{0,127}$/.test(callId)) throw new UnsafeAudioPathError('Invalid recording owner.')
  const root = path.resolve(uploadsDir)
  const owned = path.resolve(root, callId)
  if (!isInside(root, owned)) throw new UnsafeAudioPathError('Recording directory is outside uploads.')
  const stat = statIfPresent(owned)
  if (stat) {
    // A junction into another call or outside uploads does not establish ownership.
    if (!stat.isDirectory() || stat.isSymbolicLink()) throw new UnsafeAudioPathError('Recording directory is a link or not a directory.')
    if (!isInside(fs.realpathSync(root), fs.realpathSync(owned))) throw new UnsafeAudioPathError('Recording directory resolves outside uploads.')
  }
  return owned
}

/** Validate the stored reference before any database deletion or worker cancel. */
export function assertCallAudioOwnership(uploadsDir: string, callId: string, audioFile: string): void {
  const owned = ownedDirectory(uploadsDir, callId)
  // Accept separators written by either supported OS, but never absolute paths.
  if (audioFile.includes('\0') || path.posix.isAbsolute(audioFile) || path.win32.isAbsolute(audioFile)) {
    throw new UnsafeAudioPathError('Recording reference must be relative.')
  }
  const parts = audioFile.split(/[\\/]/)
  if (parts.some(part => part === '..' || part.includes(':'))) throw new UnsafeAudioPathError('Recording reference contains traversal.')
  const audio = path.resolve(uploadsDir, ...parts)
  if (!isInside(owned, audio)) throw new UnsafeAudioPathError('Recording belongs to a different directory.')

  // Check the nearest existing ancestor too: a missing file beneath a junction
  // is still not owned by this call. Missing ordinary files are safe to clean.
  let existing = audio
  while (isInside(owned, existing) && !statIfPresent(existing)) existing = path.dirname(existing)
  if (statIfPresent(existing)) {
    let real: string
    try { real = fs.realpathSync(existing) }
    catch (error) {
      if ((error as NodeJS.ErrnoException).code === 'ENOENT') throw new UnsafeAudioPathError('Recording reference contains a broken link.')
      throw error
    }
    const realOwned = fs.realpathSync(owned)
    if (real !== realOwned && !isInside(realOwned, real)) throw new UnsafeAudioPathError('Recording reference resolves outside its owner.')
  }
}

function errorDetail(error: unknown): string {
  const value = error as NodeJS.ErrnoException
  return `${value?.code ? `${value.code}: ` : ''}${value?.message ?? String(error)}`.slice(0, 1000)
}

/**
 * SQLite stores the intent before filesystem cleanup. Each job is attempted
 * once per invocation; a failure survives restart without undoing a committed
 * logical deletion. This is deliberately a local, single-process outbox.
 */
export function cleanupPendingAudio(db: DB, uploadsDir: string, callId?: string): void {
  let jobs: Array<{ call_id: string }>
  try {
    jobs = (callId === undefined
      ? db.prepare('SELECT call_id FROM audio_cleanup_jobs ORDER BY created_at, call_id').all()
      : db.prepare('SELECT call_id FROM audio_cleanup_jobs WHERE call_id=?').all(callId)) as Array<{ call_id: string }>
  } catch (error) {
    console.warn('[audio-cleanup] Could not read pending jobs:', errorDetail(error))
    return
  }
  for (const job of jobs) {
    try {
      // A stale or manually added job must never remove a live call's recording.
      if (db.prepare('SELECT 1 FROM calls WHERE id=?').get(job.call_id)) throw new Error('The recording still belongs to an existing call.')
      const owned = ownedDirectory(uploadsDir, job.call_id)
      fs.rmSync(owned, { recursive: true, force: true })
      db.prepare('DELETE FROM audio_cleanup_jobs WHERE call_id=?').run(job.call_id)
    } catch (error) {
      const detail = errorDetail(error)
      try {
        db.prepare('UPDATE audio_cleanup_jobs SET attempts=attempts+1, last_error=? WHERE call_id=?').run(detail, job.call_id)
      } catch (recordError) {
        // The original committed job remains retryable even if its diagnostic
        // update fails. Cleanup must not turn a successful deletion into HTTP500.
        console.warn('[audio-cleanup] Could not update pending job:', errorDetail(recordError))
      }
      console.warn(`[audio-cleanup] Pending ${job.call_id}: ${detail}`)
    }
  }
}
